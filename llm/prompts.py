"""Утилиты для построения промптов"""


class PromptBuilder:
    """Построить промпты с системными инструкциями"""
    
    SYSTEM_PROMPT = """Вы помощник, специализирующийся на суммировании текста.
Ваша задача - создать краткие и точные резюме, которые охватывают основные моменты входного текста.
Держите резюме кратким, но всеобъемлющим."""
    
    @staticmethod
    def build_summarize_prompt(text: str) -> tuple[str, str]:
        """Построить промпт для суммирования текста"""
        system_prompt = PromptBuilder.SYSTEM_PROMPT
        user_prompt = f"""Пожалуйста, суммируйте следующий текст в 2-3 предложения:

{text}

Предоставьте только резюме, без дополнительных объяснений."""
        
        return system_prompt, user_prompt
